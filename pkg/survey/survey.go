// Package survey estimates how much of a Go module could be defined in .af
// files: hand-written LLM tool schemas, structured-output schemas, HTTP
// handlers that only serve one sqlc query, and long prompt strings, next to
// the code agentflow and sqlc already generate.
//
// It reads source syntactically and uses heuristics, so its numbers are an
// estimate to steer migration, not a measurement.
package survey

import (
	"bytes"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"github.com/omniaura/agentflow/pkg/sqlcgo"
)

// Category is a kind of code the survey counts.
type Category string

const (
	// Hand-written code agentflow could generate.
	Tools   Category = "tool schemas"
	Outputs Category = "structured outputs"
	Routes  Category = "single-query handlers"
	Prompts Category = "prompt strings"
	Agents  Category = "tool-calling loops"

	// Code already generated.
	GenAgentflow Category = "generated by agentflow"
	GenSqlc      Category = "generated by sqlc"
	GenOther     Category = "generated by other tools"
)

// Candidates are the categories agentflow could take over.
var Candidates = []Category{Tools, Outputs, Routes, Prompts, Agents}

// Site is one counted piece of code.
type Site struct {
	File  string `json:"file"`
	Line  int    `json:"line"`
	Name  string `json:"name,omitempty"`
	Lines int    `json:"lines"`
}

// Report is the result of a survey.
type Report struct {
	Root string `json:"root"`
	// Lines are the non-test Go lines in the module, and HandWritten the
	// ones not generated.
	Lines       int `json:"lines"`
	HandWritten int `json:"hand_written"`
	// AFLines are the lines of .af files.
	AFLines int                 `json:"af_lines"`
	Sites   map[Category][]Site `json:"sites"`
}

// LinesOf sums the lines of the sites in c.
func (r *Report) LinesOf(c Category) int {
	n := 0
	for _, s := range r.Sites[c] {
		n += s.Lines
	}
	return n
}

// generatedRE matches the generated-code comment go generate tools write.
// Some, such as swag, put it after other text on the line.
var generatedRE = regexp.MustCompile(`(?m)^//.*Code generated .* DO NOT EDIT\.?`)

// Run surveys the Go module rooted at root.
func Run(root string) (*Report, error) {
	r := &Report{Root: root, Sites: map[Category][]Site{}}
	queries := sqlcQueries(root)
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if path != root && (strings.HasPrefix(d.Name(), ".") || d.Name() == "vendor" || d.Name() == "testdata" || d.Name() == "node_modules") {
				return filepath.SkipDir
			}
			return nil
		}
		switch {
		case strings.HasSuffix(path, ".af"):
			b, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			r.AFLines += lineCount(b)
		case strings.HasSuffix(path, ".go") && !strings.HasSuffix(path, "_test.go"):
			return r.file(root, path, queries)
		}
		return nil
	})
	for c := range r.Sites {
		sort.Slice(r.Sites[c], func(i, j int) bool { return r.Sites[c][i].Lines > r.Sites[c][j].Lines })
	}
	return r, err
}

func lineCount(b []byte) int {
	n := bytes.Count(b, []byte("\n"))
	if len(b) > 0 && b[len(b)-1] != '\n' {
		n++
	}
	return n
}

// sqlcQueries returns the names of the sqlc queries in the module, by the
// import path of their package.
func sqlcQueries(root string) map[string]map[string]bool {
	out := map[string]map[string]bool{}
	repo, err := sqlcgo.Find(root)
	if err != nil {
		return out
	}
	for _, p := range repo.Packages {
		names := map[string]bool{}
		for name := range p.Queries {
			names[name] = true
		}
		out[p.ImportPath] = names
	}
	return out
}

func (r *Report) file(root, path string, queries map[string]map[string]bool) error {
	src, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	rel, _ := filepath.Rel(root, path)
	n := lineCount(src)
	r.Lines += n
	if head := src[:min(len(src), 4096)]; generatedRE.Match(head) {
		c := GenOther
		switch {
		case bytes.Contains(head, []byte("Code generated by agentflow")):
			c = GenAgentflow
		case bytes.Contains(head, []byte("Code generated by sqlc")):
			c = GenSqlc
		}
		r.Sites[c] = append(r.Sites[c], Site{File: rel, Line: 1, Lines: n})
		return nil
	}
	r.HandWritten += n
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, src, parser.SkipObjectResolution)
	if err != nil {
		return nil // Not ours to report.
	}
	s := scanner{r: r, fset: fset, file: rel, src: src}
	s.sqlcNames = map[string]map[string]bool{}
	for _, imp := range f.Imports {
		p, _ := strconv.Unquote(imp.Path.Value)
		if names, ok := queries[p]; ok {
			name := p[strings.LastIndexByte(p, '/')+1:]
			if imp.Name != nil {
				name = imp.Name.Name
			}
			s.sqlcNames[name] = names
		}
	}
	// A file in a sqlc package calls its queries unqualified.
	for p, names := range queries {
		if strings.HasSuffix(p, "/"+f.Name.Name) {
			s.localQueries = names
		}
	}
	s.scan(f)
	return nil
}

type scanner struct {
	r            *Report
	fset         *token.FileSet
	file         string
	src          []byte
	sqlcNames    map[string]map[string]bool
	localQueries map[string]bool
	// counted are the ranges already attributed, so nested matches count
	// once.
	counted [][2]token.Pos
}

func (s *scanner) add(c Category, n ast.Node, name string) {
	for _, r := range s.counted {
		if n.Pos() >= r[0] && n.End() <= r[1] {
			return
		}
	}
	s.counted = append(s.counted, [2]token.Pos{n.Pos(), n.End()})
	start, end := s.fset.Position(n.Pos()), s.fset.Position(n.End())
	s.r.Sites[c] = append(s.r.Sites[c], Site{File: s.file, Line: start.Line, Name: name, Lines: end.Line - start.Line + 1})
}

func (s *scanner) scan(f *ast.File) {
	for _, d := range f.Decls {
		if fn, ok := d.(*ast.FuncDecl); ok && isHandler(fn.Type) && fn.Body != nil {
			if q := s.singleQuery(fn.Body); q != "" {
				s.add(Routes, fn, fn.Name.Name+" → "+q)
			}
		}
	}
	// stack holds the enclosing nodes, so a schema is counted with the
	// declaration or statement that builds it, such as helper calls that
	// add its parameters.
	var stack []ast.Node
	ast.Inspect(f, func(n ast.Node) bool {
		if n == nil {
			stack = stack[:len(stack)-1]
			return true
		}
		stack = append(stack, n)
		switch n := n.(type) {
		case *ast.CompositeLit:
			if c, ok := s.schemaKind(n); ok {
				s.add(c, enclosing(stack), typeName(n.Type))
			}
		case *ast.BasicLit:
			if n.Kind == token.STRING && isPrompt(n.Value) {
				s.add(Prompts, n, "")
			}
		case *ast.ForStmt, *ast.RangeStmt:
			if isAgentLoop(n) {
				site, name := s.agentSite(stack)
				s.add(Agents, site, name)
			}
		}
		return true
	})
}

// Names that mark code reading a model's tool calls, and code answering
// them, across the provider SDKs.
var (
	toolCallNames   = []string{"ToolCalls", "ToolUse", "ToolUseBlock", "FunctionCall", "FunctionCalls"}
	toolResultNames = []string{"NewToolResultBlock", "ToolResultBlockParam", "ToolMessage", "ToolCallID", "ToolUseID", "NewPartFromFunctionResponse", "FunctionResponse"}
)

// isAgentLoop reports whether a loop calls a model, reads its tool calls
// and builds results for them: the core of a hand-written tool-calling
// loop. Code that only converts transcripts reads calls and results too,
// but sends no request.
func isAgentLoop(loop ast.Node) bool {
	var calls, results, ctxCall bool
	ast.Inspect(loop, func(n ast.Node) bool {
		var name string
		switch n := n.(type) {
		case *ast.Ident:
			name = n.Name
		case *ast.BasicLit:
			// Hand-built JSON maps: {"role": "tool", "tool_call_id": ...}.
			name = stringLit(n)
		case *ast.CallExpr:
			ctxCall = ctxCall || isContextCall(n)
		}
		calls = calls || slices.Contains(toolCallNames, name) || name == "tool_calls" || name == "tool_use"
		results = results || slices.Contains(toolResultNames, name) || name == "tool_call_id" || name == "tool_result"
		return !(calls && results && ctxCall)
	})
	return calls && results && ctxCall
}

// modelCallWords are words in the names of methods that send a request
// to a model.
var modelCallWords = []string{"new", "create", "complet", "chat", "stream", "generat", "infer", "send"}

// isContextCall reports whether call looks like a model request: a method
// named like one, whose first argument is a context (ctx, turnCtx, or
// r.Context()).
func isContextCall(call *ast.CallExpr) bool {
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok || len(call.Args) == 0 {
		return false
	}
	name := strings.ToLower(sel.Sel.Name)
	if !slices.ContainsFunc(modelCallWords, func(w string) bool { return strings.Contains(name, w) }) {
		return false
	}
	switch a := call.Args[0].(type) {
	case *ast.Ident:
		// ctx, or a derived turnCtx, reqCtx...
		return strings.Contains(strings.ToLower(a.Name), "ctx")
	case *ast.CallExpr:
		sel, ok := a.Fun.(*ast.SelectorExpr)
		return ok && sel.Sel.Name == "Context"
	}
	return false
}

// agentSite returns the function that holds the loop at the top of stack,
// which is the agent's setup, loop and result, or just the loop when the
// function is too long to be only that.
func (s *scanner) agentSite(stack []ast.Node) (ast.Node, string) {
	loop := stack[len(stack)-1]
	for i := len(stack) - 2; i >= 0; i-- {
		switch fn := stack[i].(type) {
		case *ast.FuncDecl:
			if s.fset.Position(fn.End()).Line-s.fset.Position(fn.Pos()).Line > 150 {
				return loop, fn.Name.Name
			}
			return fn, fn.Name.Name
		case *ast.FuncLit:
			return fn, ""
		}
	}
	return loop, ""
}

// enclosing returns the outermost variable declaration in stack, or else
// the innermost statement, or else the last node.
func enclosing(stack []ast.Node) ast.Node {
	for _, n := range stack {
		if v, ok := n.(*ast.ValueSpec); ok {
			return v
		}
	}
	for i := len(stack) - 1; i >= 0; i-- {
		if st, ok := stack[i].(ast.Stmt); ok {
			if _, block := st.(*ast.BlockStmt); !block {
				return st
			}
		}
	}
	return stack[len(stack)-1]
}

// isHandler reports whether ft is func(http.ResponseWriter, *http.Request).
func isHandler(ft *ast.FuncType) bool {
	var params []ast.Expr
	for _, p := range ft.Params.List {
		for range max(1, len(p.Names)) {
			params = append(params, p.Type)
		}
	}
	if len(params) != 2 || ft.Results != nil {
		return false
	}
	w, ok1 := params[0].(*ast.SelectorExpr)
	r, ok2 := params[1].(*ast.StarExpr)
	if !ok1 || !ok2 || w.Sel.Name != "ResponseWriter" {
		return false
	}
	rs, ok := r.X.(*ast.SelectorExpr)
	return ok && rs.Sel.Name == "Request"
}

// singleQuery returns the sqlc query a handler body calls, when it calls
// exactly one and is short enough to be glue: decode, query, respond.
func (s *scanner) singleQuery(body *ast.BlockStmt) string {
	var calls []string
	ast.Inspect(body, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		sel, ok := call.Fun.(*ast.SelectorExpr)
		if !ok {
			return true
		}
		if s.isQuery(sel.Sel.Name, call) {
			calls = append(calls, sel.Sel.Name)
		}
		return true
	})
	if len(calls) != 1 {
		return ""
	}
	start, end := s.fset.Position(body.Lbrace), s.fset.Position(body.Rbrace)
	if end.Line-start.Line > 60 {
		return "" // Too much else going on to be a plain route.
	}
	return calls[0]
}

// isQuery reports whether a call to a method named name is a sqlc query:
// the name is a query and an argument is the package's Params type, or the
// file is in or imports the sqlc package and the name is unambiguous.
func (s *scanner) isQuery(name string, call *ast.CallExpr) bool {
	if s.localQueries[name] {
		return true
	}
	for pkg, names := range s.sqlcNames {
		if !names[name] {
			continue
		}
		for _, a := range call.Args {
			if lit, ok := a.(*ast.CompositeLit); ok {
				if sel, ok := lit.Type.(*ast.SelectorExpr); ok {
					if x, ok := sel.X.(*ast.Ident); ok && x.Name == pkg {
						return true
					}
				}
			}
		}
		// Single-argument queries take no Params struct.
		return len(call.Args) <= 2
	}
	return false
}

var (
	toolTypes   = []string{"FunctionDefinitionParam", "ToolParam", "ToolUnionParam", "ChatCompletionToolParam", "FunctionTool", "FunctionDeclaration"}
	outputTypes = []string{"ResponseFormatJSONSchemaParam", "ResponseFormatJSONSchemaJSONSchemaParam", "JSONSchemaOutputFormatParam", "OutputFormatParam"}
)

func typeName(e ast.Expr) string {
	switch e := e.(type) {
	case *ast.Ident:
		return e.Name
	case *ast.SelectorExpr:
		return typeName(e.X) + "." + e.Sel.Name
	case *ast.IndexExpr:
		return typeName(e.X)
	case *ast.MapType:
		return "map"
	}
	return ""
}

// schemaKind classifies a composite literal that defines an LLM tool or a
// structured output: a provider SDK's tool or response-format type, or a
// JSON Schema object written as a map with "type": "object" and
// "properties".
func (s *scanner) schemaKind(lit *ast.CompositeLit) (Category, bool) {
	name := typeName(lit.Type)
	base := name[strings.LastIndexByte(name, '.')+1:]
	switch {
	case slices.Contains(toolTypes, base):
		return Tools, true
	case slices.Contains(outputTypes, base):
		return Outputs, true
	case name == "map":
		var hasObject, hasProps bool
		for _, e := range lit.Elts {
			kv, ok := e.(*ast.KeyValueExpr)
			if !ok {
				continue
			}
			key := stringLit(kv.Key)
			hasProps = hasProps || key == "properties"
			hasObject = hasObject || (key == "type" && stringLit(kv.Value) == "object")
		}
		if hasObject && hasProps {
			return Tools, true
		}
	}
	return "", false
}

func stringLit(e ast.Expr) string {
	if b, ok := e.(*ast.BasicLit); ok && b.Kind == token.STRING {
		s, _ := strconv.Unquote(b.Value)
		return s
	}
	return ""
}

// isPrompt reports whether a string literal reads like a prompt: long,
// mostly prose, and addressed to a model.
func isPrompt(lit string) bool {
	if len(lit) < 300 {
		return false
	}
	s, err := strconv.Unquote(lit)
	if err != nil {
		return false
	}
	letters, spaces := 0, 0
	for _, r := range s {
		switch {
		case unicode.IsLetter(r):
			letters++
		case unicode.IsSpace(r):
			spaces++
		}
	}
	if float64(letters+spaces) < 0.85*float64(len([]rune(s))) || strings.HasPrefix(strings.TrimSpace(s), "{") {
		return false // Code, SQL, JSON or data.
	}
	lower := strings.ToLower(s)
	first, _, _ := strings.Cut(strings.TrimSpace(lower), " ")
	if slices.Contains([]string{"select", "insert", "update", "delete", "with", "create", "alter", "drop"}, first) {
		return false
	}
	for _, cue := range []string{"you are", "you will", "your task", "respond with", "return ", "do not", "never ", "always "} {
		if strings.Contains(lower, cue) {
			return true
		}
	}
	return false
}
