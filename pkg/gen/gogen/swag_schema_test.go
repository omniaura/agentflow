package gogen

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/omniaura/agentflow/pkg/ast"
	"github.com/omniaura/agentflow/pkg/sqlcgo"
	"github.com/swaggo/swag"
)

// Parse the generated annotations with the same Swag version used by the
// route-generation fixtures. Annotation text alone cannot detect responses
// overwriting one another in the emitted Swagger document.
func TestEmptySuccessSwaggerSchema(t *testing.T) {
	repo, err := sqlcgo.Find("../../../examples/routes")
	if err != nil {
		t.Fatal(err)
	}
	for _, tc := range []struct {
		name, empty string
		union       bool
		extraStatus int
	}{
		{"normal only", "", false, 0},
		{"same status function", ".empty 200 draft\n", true, 0},
		{"same status string", ".empty 200 \"missing\"\n", true, 0},
		{"same status null", ".empty 200 null\n", true, 0},
		{"same status array", ".empty 200 []\n", true, 0},
		{"different status function", ".empty 201 draft\n", false, 201},
		{"bodyless 204", ".empty 204\n", false, 204},
		{"bodyless 205", ".empty 205\n", false, 205},
	} {
		t.Run(tc.name, func(t *testing.T) {
			f, err := ast.NewFile("todos.af", []byte(".route GET /todos/{id} GetTodo\n.auth owner_id\n.map normal\n"+tc.empty))
			if err != nil {
				t.Fatal(err)
			}
			var generated bytes.Buffer
			err = GenFileOptions(&generated, f, "api", Options{Queries: repo.Lookup, MapFuncs: map[string]MapFunc{"normal": {Params: []string{"row"}, Result: "Normal"}}, EmptyFuncs: map[string]MapFunc{"draft": {Result: "Draft"}}, Swag: &Swag{}})
			if err != nil {
				t.Fatal(err)
			}
			// External error-model resolution is independent of the success contract.
			var lines []string
			for _, line := range strings.Split(generated.String(), "\n") {
				if !strings.HasPrefix(line, "// @Failure ") {
					lines = append(lines, line)
				}
			}
			dir := t.TempDir()
			for name, src := range map[string]string{
				"go.mod":      "module example.com/swaggerfixture\n\ngo 1.27\n",
				"info.go":     "// @title Empty success regression\n// @version 1.0\npackage api\ntype Normal struct { Value string `json:\"value\"` }\ntype Draft struct { Note string `json:\"note\"` }\n",
				"todos_af.go": strings.Join(lines, "\n"),
			} {
				if err := os.WriteFile(filepath.Join(dir, name), []byte(src), 0600); err != nil {
					t.Fatal(err)
				}
			}
			parser := swag.New()
			if err := parser.ParseAPI(dir, "info.go", 0); err != nil {
				t.Fatal(err)
			}
			doc := parser.GetSwagger()
			op := doc.Paths.Paths["/todos/{id}"].Get
			if op == nil {
				t.Fatal("generated operation missing")
			}
			resp, ok := op.Responses.StatusCodeResponses[200]
			if !ok || resp.Schema == nil {
				t.Fatal("200 success schema missing")
			}
			raw, err := json.Marshal(doc)
			if err != nil {
				t.Fatal(err)
			}
			var wire map[string]any
			if err := json.Unmarshal(raw, &wire); err != nil {
				t.Fatal(err)
			}
			if tc.union {
				schema, err := json.Marshal(resp.Schema)
				if err != nil {
					t.Fatal(err)
				}
				if string(schema) != "{}" {
					t.Fatalf("shared-status schema must accept both variants, got %s", schema)
				}
				if !strings.Contains(resp.Description, "Normal") || !strings.Contains(resp.Description, "empty result:") {
					t.Fatalf("missing variant description: %s", resp.Description)
				}
				operation := wire["paths"].(map[string]any)["/todos/{id}"].(map[string]any)["get"].(map[string]any)
				variants := operation["x-agentflow-response-variants"].(map[string]any)["200"].([]any)
				if len(variants) != 2 || variants[0].(map[string]any)["goType"] != "Normal" {
					t.Fatalf("variants lost: %#v", variants)
				}
				empty := variants[1].(map[string]any)
				if strings.Contains(tc.empty, "draft") {
					if empty["goType"] != "Draft" || !strings.Contains(resp.Description, "Draft") {
						t.Fatalf("empty type lost: %#v", empty)
					}
				} else {
					want := strings.TrimSpace(strings.TrimPrefix(tc.empty, ".empty 200 "))
					got, err := json.Marshal(empty["json"])
					if err != nil || string(got) != want {
						t.Fatalf("empty JSON = %s, want %s (%v)", got, want, err)
					}
				}
			} else {
				if !strings.Contains(resp.Schema.Ref.String(), "Normal") {
					t.Fatalf("normal schema changed: %#v", resp.Schema)
				}
				if tc.extraStatus != 0 {
					extra, ok := op.Responses.StatusCodeResponses[tc.extraStatus]
					if !ok {
						t.Fatalf("missing status %d", tc.extraStatus)
					}
					if tc.extraStatus == 201 && (extra.Schema == nil || !strings.Contains(extra.Schema.Ref.String(), "Draft")) {
						t.Fatal("separate empty schema lost")
					}
					if tc.extraStatus >= 204 && extra.Schema != nil {
						t.Fatal("bodyless response acquired a schema")
					}
				}
			}
		})
	}
}
