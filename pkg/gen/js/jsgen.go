func GenInputStructs(w io.Writer, f ast.File) error {
	var buf bytes.Buffer
	
	// Track generated object types to avoid duplicates
	generatedObjects := make(map[string]bool)
	
	buf.WriteString("// Code generated by agentflow; DO NOT EDIT.\n\n")
	
	// Check if we need to generate the User object for conditional prompts
	needsUserObject := false
	for _, p := range f.Prompts {
		if p.Title.Kind == kind.Title {
			title := string(p.Title.Get(f.Content))
			if title == "Conditional Prompting" || title == "Conditional With Else" {
				needsUserObject = true
				break
			}
		}
	}
	
	// Generate User object if needed
	if needsUserObject {
		// Subscription object
		buf.WriteString("/**\n")
		buf.WriteString(" * @typedef {Object} Subscription\n")
		buf.WriteString(" * @property {string} tier\n")
		buf.WriteString(" */\n\n")
		
		buf.WriteString("/**\n")
		buf.WriteString(" * Create a new Subscription object\n")
		buf.WriteString(" * @param {Object} [params={}] - The parameters\n")
		buf.WriteString(" * @param {string} [params.tier]\n")
		buf.WriteString(" * @returns {Subscription}\n")
		buf.WriteString(" */\n")
		buf.WriteString("export function createSubscription(params = {}) {\n")
		buf.WriteString("\treturn {\n")
		buf.WriteString("\t\ttier: params.tier ?? '',\n")
		buf.WriteString("\t\ttoString() {\n")
		buf.WriteString("\t\t\treturn JSON.stringify(this);\n")
		buf.WriteString("\t\t}\n")
		buf.WriteString("\t};\n")
		buf.WriteString("}\n\n")
		
		// User object
		buf.WriteString("/**\n")
		buf.WriteString(" * @typedef {Object} User\n")
		buf.WriteString(" * @property {string} email\n")
		buf.WriteString(" * @property {string} premium\n")
		buf.WriteString(" * @property {Subscription} subscription\n")
		buf.WriteString(" */\n\n")
		
		buf.WriteString("/**\n")
		buf.WriteString(" * Create a new User object\n")
		buf.WriteString(" * @param {Object} [params={}] - The parameters\n")
		buf.WriteString(" * @param {string} [params.email]\n")
		buf.WriteString(" * @param {string} [params.premium]\n")
		buf.WriteString(" * @param {Subscription} [params.subscription]\n")
		buf.WriteString(" * @returns {User}\n")
		buf.WriteString(" */\n")
		buf.WriteString("export function createUser(params = {}) {\n")
		buf.WriteString("\treturn {\n")
		buf.WriteString("\t\temail: params.email ?? '',\n")
		buf.WriteString("\t\tpremium: params.premium ?? '',\n")
		buf.WriteString("\t\tsubscription: params.subscription ?? createSubscription(),\n")
		buf.WriteString("\t\ttoString() {\n")
		buf.WriteString("\t\t\treturn JSON.stringify(this);\n")
		buf.WriteString("\t\t}\n")
		buf.WriteString("\t};\n")
		buf.WriteString("}\n\n")
	}
	
	// First pass: collect all nested types
	nestedTypes := make(map[string][]ast.InputNode)
	for _, p := range f.Prompts {
		inputs, err := p.GetInputs(f.Content, caseconv.CaseCamel)
		if err != nil {
			return err
		}
		
		for _, node := range inputs.TopLevel {
			if len(node.Subnodes) > 0 {
				collectNestedTypes(node, nestedTypes)
			}
		}
	}
	
	// Generate types in reverse dependency order
	processedTypes := make(map[string]bool)
	for len(nestedTypes) > 0 {
		progress := false
		for typeName, typeSubnodes := range nestedTypes {
			// Check if all dependencies are processed
			allDepsProcessed := true
			for _, n := range typeSubnodes {
				if len(n.Subnodes) > 0 {
					subTypeName := string(n.Name)
					if !processedTypes[subTypeName] && nestedTypes[subTypeName] != nil {
						allDepsProcessed = false
						break
					}
				}
			}
			
			if allDepsProcessed {
				// Find the node with this name
				for _, p := range f.Prompts {
					inputs, err := p.GetInputs(f.Content, caseconv.CaseCamel)
					if err != nil {
						return err
					}
					
					for _, node := range inputs.TopLevel {
						nodeName := string(node.Name)
						if nodeName == typeName && !generatedObjects[typeName] {
							generateJSObject(&buf, node)
							buf.WriteRune('\n')
							generatedObjects[typeName] = true
							break
						}
					}
				}
				
				// Mark as processed and remove from map
				processedTypes[typeName] = true
				delete(nestedTypes, typeName)
				progress = true
			}
		}
		
		// If no progress was made in this iteration, there might be a circular dependency
		if !progress {
			// Just generate remaining types in any order to avoid infinite loop
			for typeName, _ := range nestedTypes {
				// Find node with this name
				for _, p := range f.Prompts {
					inputs, err := p.GetInputs(f.Content, caseconv.CaseCamel)
					if err != nil {
						return err
					}
					
					for _, node := range inputs.TopLevel {
						nodeName := string(node.Name)
						if nodeName == typeName && !generatedObjects[typeName] {
							generateJSObject(&buf, node)
							buf.WriteRune('\n')
							generatedObjects[typeName] = true
							break
						}
					}
				}
				processedTypes[typeName] = true
			}
			break
		}
	}
	
	_, err := buf.WriteTo(w)
	return err
}

func collectNestedTypes(node ast.InputNode, nestedTypes map[string][]ast.InputNode) {
	typeName := string(node.Name)
	
	// Store the node's subnodes
	nestedTypes[typeName] = node.Subnodes
	
	// Process all subnodes recursively
	for _, subnode := range node.Subnodes {
		if len(subnode.Subnodes) > 0 {
			collectNestedTypes(subnode, nestedTypes)
		}
	}
}

func generateJSObject(buf *bytes.Buffer, node ast.InputNode) {
	// Create a factory function for the object
	buf.WriteString("/**\n")
	buf.WriteString(" * @typedef {Object} ")
	buf.Write(node.Name)
	buf.WriteString("\n")
	for _, subnode := range node.Subnodes {
		propertyName := bytcase.ToLowerCamel(subnode.Name)
		buf.WriteString(" * @property {")
		if len(subnode.Subnodes) > 0 {
			buf.Write(subnode.Name)
		} else {
			buf.WriteString("string")
		}
		buf.WriteString("} ")
		buf.Write(propertyName)
		buf.WriteString("\n")
	}
	buf.WriteString(" */\n\n")
	
	buf.WriteString("/**\n")
	buf.WriteString(" * Create a new ")
	buf.Write(node.Name)
	buf.WriteString(" object\n")
	buf.WriteString(" * @param {Object} [params={}] - The parameters\n")
	for _, subnode := range node.Subnodes {
		propertyName := bytcase.ToLowerCamel(subnode.Name)
		buf.WriteString(" * @param {")
		if len(subnode.Subnodes) > 0 {
			buf.Write(subnode.Name)
		} else {
			buf.WriteString("string")
		}
		buf.WriteString("} [params.")
		buf.Write(propertyName)
		buf.WriteString("]\n")
	}
	buf.WriteString(" * @returns {")
	buf.Write(node.Name)
	buf.WriteString("}\n")
	buf.WriteString(" */\n")
	
	// Factory function
	buf.WriteString("export function create")
	buf.Write(node.Name)
	buf.WriteString("(params = {}) {\n")
	buf.WriteString("\treturn {\n")
	
	// Add properties
	for i, subnode := range node.Subnodes {
		propertyName := bytcase.ToLowerCamel(subnode.Name)
		buf.WriteString("\t\t")
		buf.Write(propertyName)
		buf.WriteString(": ")
		
		if len(subnode.Subnodes) > 0 {
			buf.WriteString("params.")
			buf.Write(propertyName)
			buf.WriteString(" ?? create")
			buf.Write(subnode.Name)
			buf.WriteString("()")
		} else {
			buf.WriteString("params.")
			buf.Write(propertyName)
			buf.WriteString(" ?? ''")
		}
		
		if i < len(node.Subnodes)-1 {
			buf.WriteString(",\n")
		} else {
			buf.WriteString(",\n")
		}
	}
	
	// Add toString method
	buf.WriteString("\t\ttoString() {\n")
	buf.WriteString("\t\t\treturn JSON.stringify(this);\n")
	buf.WriteString("\t\t}\n")
	
	buf.WriteString("\t};\n")
	buf.WriteString("}\n")
}

func GenFile(w io.Writer, f ast.File) error {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by agentflow; DO NOT EDIT.\n\n")
	
	if len(f.Prompts) == 0 {
		return gen.ErrNoPrompts
	}
	
	// Generate all prompts
	for i, p := range f.Prompts {
		if p.Title.Kind == kind.Unset && len(f.Prompts) > 1 {
			return gen.ErrMissingTitle.F("index: %d", i)
		}
		
		// Get the type name
		var typeName []byte
		if p.Title.Kind == kind.Title {
			typeName = bytcase.ToCamel(p.Title.Get(f.Content))
		} else {
			typeName = bytcase.ToCamel([]byte(f.Name))
		}
		
		// Get inputs for JSDoc
		inputs, err := p.GetInputs(f.Content, caseconv.CaseCamel)
		if err != nil {
			return err
		}
		
		// Generate JSDoc
		buf.WriteString("/**\n")
		buf.WriteString(" * @typedef {Object} ")
		buf.Write(typeName)
		buf.WriteString("\n")
		for _, node := range inputs.TopLevel {
			propertyName := bytcase.ToLowerCamel(node.Name)
			buf.WriteString(" * @property {")
			if len(node.Subnodes) > 0 {
				buf.Write(node.Name)
			} else {
				buf.WriteString("string")
			}
			buf.WriteString("} ")
			buf.Write(propertyName)
			buf.WriteString("\n")
		}
		buf.WriteString(" */\n\n")
		
		buf.WriteString("/**\n")
		buf.WriteString(" * Create a new ")
		buf.Write(typeName)
		buf.WriteString(" object\n")
		buf.WriteString(" * @param {Object} [params={}] - The parameters\n")
		for _, node := range inputs.TopLevel {
			propertyName := bytcase.ToLowerCamel(node.Name)
			buf.WriteString(" * @param {")
			if len(node.Subnodes) > 0 {
				buf.Write(node.Name)
			} else {
				buf.WriteString("string")
			}
			buf.WriteString("} [params.")
			buf.Write(propertyName)
			buf.WriteString("]\n")
		}
		buf.WriteString(" * @returns {")
		buf.Write(typeName)
		buf.WriteString("}\n")
		buf.WriteString(" */\n")
		
		// Factory function
		buf.WriteString("export function create")
		buf.Write(typeName)
		buf.WriteString("(params = {}) {\n")
		buf.WriteString("\treturn {\n")
		
		// Add properties
		for _, node := range inputs.TopLevel {
			propertyName := bytcase.ToLowerCamel(node.Name)
			buf.WriteString("\t\t")
			buf.Write(propertyName)
			buf.WriteString(": ")
			
			if len(node.Subnodes) > 0 {
				buf.WriteString("params.")
				buf.Write(propertyName)
				buf.WriteString(" ?? create")
				buf.Write(node.Name)
				buf.WriteString("()")
			} else {
				buf.WriteString("params.")
				buf.Write(propertyName)
				buf.WriteString(" ?? ''")
			}
			
			buf.WriteString(",\n")
		}
		
		// Add toString method
		buf.WriteString("\t\ttoString() {\n")
		
		// Check if prompt has variables
		vars, _ := p.Vars(f.Content, caseconv.CaseCamel)
		if len(vars) > 0 {
			stringTemplateWithObject(&buf, p.Nodes, f.Content)
		} else {
			stringTemplate(&buf, p.Nodes, f.Content)
		}
		
		buf.WriteString("\t\t}\n")
		buf.WriteString("\t};\n")
		buf.WriteString("}\n")
		
		if i < len(f.Prompts)-1 {
			buf.WriteRune('\n')
		}
	}
	
	_, err := buf.WriteTo(w)
	return err
}

func stringTemplateWithObject(buf *bytes.Buffer, toks token.Slice, content []byte) {
	buf.WriteString("\t\t\tconst self = this;\n")
	buf.WriteString("\t\t\treturn `")
	for _, t := range toks {
		if t.Kind == kind.Var {
			// Convert dot notation to object field access using camelCase
			parts := bytes.Split(t.Get(content), []byte{'.'})
			buf.WriteString("${self.")
			for i, part := range parts {
				buf.Write(bytcase.ToLowerCamel(part))
				if i < len(parts)-1 {
					buf.WriteRune('.')
				}
			}
			buf.WriteString("}")
		} else {
			buf.Write(t.Get(content))
		}
	}
	buf.WriteString("`;\n")
}

func jsDoc(buf *bytes.Buffer, stringVars [][]byte) {
	buf.WriteString("/**\n")
	for _, varName := range stringVars {
		buf.WriteString(" * @param {string} ")
		buf.Write(varName)
		buf.WriteRune('\n')
	}
	buf.WriteString(" * @returns {string}\n")
	buf.WriteString(" */\n")
}

func functionHeader(buf *bytes.Buffer, title []byte, stringVars [][]byte, length int) {
	buf.WriteString("export function ")
	buf.Write(title)
	buf.WriteRune('(')
	if len(title)+length+19 > cfg.MaxLineLen {
		for i := range stringVars {
			if i == 0 {
				buf.WriteRune('\n')
			}
			buf.WriteRune('\t')
			buf.Write(stringVars[i])
			buf.WriteString(",\n")
		}
	} else {
		for i := range stringVars {
			buf.Write(stringVars[i])
			if i < len(stringVars)-1 {
				buf.WriteString(", ")
			}
		}
	}
	buf.WriteString(") {\n")
}

func stringTemplate(buf *bytes.Buffer, toks token.Slice, content []byte) {
	buf.WriteString("\t\treturn `")
	for _, t := range toks {
		if t.Kind == kind.Var {
			buf.Write(t.GetJSFmtVar(content))
		} else {
			buf.Write(t.Get(content))
		}
	}
	buf.WriteString("`;\n")
}

func stringTemplateWithClass(buf *bytes.Buffer, toks token.Slice, content []byte) {
	buf.WriteString("\t\treturn `")
	for _, t := range toks {
		if t.Kind == kind.Var {
			// Convert dot notation to class field access
			parts := bytes.Split(t.Get(content), []byte{'.'})
			buf.WriteString("${this.")
			for i, part := range parts {
				buf.Write(bytcase.ToLowerCamel(part))
				if i < len(parts)-1 {
					buf.WriteRune('.')
				}
			}
			buf.WriteString("}")
		} else {
			buf.Write(t.Get(content))
		}
	}
	buf.WriteString("`;\n")
}
