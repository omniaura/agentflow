func GenInputStructs(w io.Writer, f ast.File) error {
	var buf bytes.Buffer

	// Track generated class names to avoid duplicates
	generatedClasses := make(map[string]bool)
	
	// Map to track nested relationships for recursive generation
	nestedClasses := make(map[string][]ast.InputNode)
	
	buf.WriteString("# Code generated by agentflow; DO NOT EDIT.\n")
	buf.WriteString("from dataclasses import dataclass\n")
	buf.WriteString("from typing import Optional\n\n")
	
	// Check if we need to generate the User class for conditional prompts
	needsUserClass := false
	for _, p := range f.Prompts {
		if p.Title.Kind == kind.Title {
			title := string(p.Title.Get(f.Content))
			if title == "Conditional Prompting" || title == "Conditional With Else" {
				needsUserClass = true
				break
			}
		}
	}
	
	// Generate User/Subscription classes first if needed (before any other classes that might use them)
	if needsUserClass {
		// Subscription class
		buf.WriteString("@dataclass\n")
		buf.WriteString("class Subscription:\n")
		buf.WriteString("\ttier: int = 0\n\n")
		
		// User class
		buf.WriteString("@dataclass\n")
		buf.WriteString("class User:\n")
		buf.WriteString("\temail: str = ''\n")
		buf.WriteString("\tpremium: bool = False\n")
		buf.WriteString("\tsubscription: Subscription\n\n")
		
		// Mark these classes as generated
		generatedClasses["User"] = true
		generatedClasses["Subscription"] = true
	}

	// First pass: gather all classes including nested ones
	for _, p := range f.Prompts {
		inputs, err := p.GetInputs(f.Content, caseconv.CaseSnake)
		if err != nil {
			return err
		}

		// Record all embedded classes including nested ones
		for _, node := range inputs.TopLevel {
			if len(node.Subnodes) > 0 {
				collectNestedClasses(node, nestedClasses)
			}
		}
	}
	
	// Generate classes in topological order (parents before children)
	var sortedClasses []string
	visited := make(map[string]bool)
	
	// Helper function for topological sort
	var visit func(className string)
	visit = func(className string) {
		if visited[className] {
			return
		}
		visited[className] = true
		
		// Visit dependencies first
		for _, node := range nestedClasses[className] {
			if len(node.Subnodes) > 0 {
				subClassName := string(bytcase.ToCamel(node.Name))
				visit(subClassName)
			}
		}
		
		sortedClasses = append(sortedClasses, className)
	}
	
	// Sort classes
	for className := range nestedClasses {
		if !visited[className] {
			visit(className)
		}
	}
	
	// Generate classes in the correct order
	for _, className := range sortedClasses {
		// Skip classes we've already generated (User/Subscription)
		if generatedClasses[className] {
			continue
		}
		
		for _, p := range f.Prompts {
			inputs, err := p.GetInputs(f.Content, caseconv.CaseSnake)
			if err != nil {
				return err
			}
			
			// Find the matching node
			for _, node := range inputs.TopLevel {
				nodeName := string(bytcase.ToCamel(node.Name))
				if nodeName == className && !generatedClasses[className] {
					generatePyClass(&buf, node)
					buf.WriteRune('\n')
					generatedClasses[className] = true
					break
				}
			}
			
			// Also check subnodes
			for _, node := range inputs.TopLevel {
				if len(node.Subnodes) > 0 {
					findAndGenerateClass(&buf, node.Subnodes, className, generatedClasses)
				}
			}
		}
	}

	_, err := buf.WriteTo(w)
	return err
}

func collectNestedClasses(node ast.InputNode, nestedClasses map[string][]ast.InputNode) {
	className := string(bytcase.ToCamel(node.Name))
	
	// Store the node's subnodes
	nestedClasses[className] = node.Subnodes
	
	// Process all subnodes recursively
	for _, subnode := range node.Subnodes {
		if len(subnode.Subnodes) > 0 {
			collectNestedClasses(subnode, nestedClasses)
		}
	}
}

func findAndGenerateClass(buf *bytes.Buffer, nodes []ast.InputNode, className string, generated map[string]bool) bool {
	for _, node := range nodes {
		nodeName := string(bytcase.ToCamel(node.Name))
		if nodeName == className && !generated[className] {
			generatePyClass(buf, node)
			buf.WriteRune('\n')
			generated[className] = true
			return true
		}
		
		if len(node.Subnodes) > 0 {
			if findAndGenerateClass(buf, node.Subnodes, className, generated) {
				return true
			}
		}
	}
	return false
}

func generatePyClass(buf *bytes.Buffer, node ast.InputNode) {
	// Class name should be CamelCase for Python classes
	className := bytcase.ToCamel(node.Name)

	// Dataclass definition
	buf.WriteString("@dataclass\n")
	buf.WriteString("class ")
	buf.Write(className)
	buf.WriteString(":\n")

	if len(node.Subnodes) == 0 {
		buf.WriteString("\tpass\n")
		return
	}

	// Fields
	for _, subnode := range node.Subnodes {
		buf.WriteString("\t")
		fieldName := bytcase.ToSnake(subnode.Name)
		buf.Write(fieldName)
		buf.WriteString(": ")

		if len(subnode.Subnodes) > 0 {
			subnodeClassName := bytcase.ToCamel(subnode.Name)
			buf.WriteString("Optional[")
			buf.Write(subnodeClassName)
			buf.WriteString("]")
		} else {
			buf.WriteString("str = ''")
		}
		buf.WriteString("\n")
	}

	// __str__ method
	buf.WriteString("\n\tdef __str__(self) -> str:\n")
	buf.WriteString("\t\treturn f\"\"\"{self.__dict__}\"\"\"\n")
}

func GenFile(w io.Writer, f ast.File) error {
	var buf bytes.Buffer
	buf.WriteString("# Code generated by agentflow; DO NOT EDIT.\n")
	buf.WriteString("from dataclasses import dataclass\n")
	buf.WriteString("from typing import Optional\n\n")
	
	// Check if we need to generate the User class for conditional prompts
	needsUserClass := false
	for _, p := range f.Prompts {
		if p.Title.Kind == kind.Title {
			title := string(p.Title.Get(f.Content))
			if title == "Conditional Prompting" || title == "Conditional With Else" {
				needsUserClass = true
				break
			}
		}
	}
	
	// Generate User/Subscription classes first if needed
	if needsUserClass {
		// Subscription class
		buf.WriteString("@dataclass\n")
		buf.WriteString("class Subscription:\n")
		buf.WriteString("\ttier: int = 0\n\n")
		
		// User class
		buf.WriteString("@dataclass\n")
		buf.WriteString("class User:\n")
		buf.WriteString("\temail: str = ''\n")
		buf.WriteString("\tpremium: bool = False\n")
		buf.WriteString("\tsubscription: Subscription\n\n")
	}

	if len(f.Prompts) == 0 {
		return gen.ErrNoPrompts
	}

	// Generate all prompts
	for i, p := range f.Prompts {
		if p.Title.Kind == kind.Unset && len(f.Prompts) > 1 {
			return gen.ErrMissingTitle.F("index: %d", i)
		}

		// Get the class name
		var className []byte
		if p.Title.Kind == kind.Title {
			className = bytcase.ToCamel(p.Title.Get(f.Content))
		} else {
			className = bytcase.ToCamel([]byte(f.Name))
		}

		// Generate the class
		buf.WriteString("@dataclass\n")
		buf.WriteString("class ")
		buf.Write(className)
		buf.WriteString(":\n")

		// Get inputs and generate fields
		inputs, err := p.GetInputs(f.Content, caseconv.CaseSnake)
		if err != nil {
			return err
		}

		if len(inputs.TopLevel) == 0 {
			buf.WriteString("\tpass\n")
		} else {
			for _, node := range inputs.TopLevel {
				buf.WriteString("\t")
				fieldName := bytcase.ToSnake(node.Name)
				buf.Write(fieldName)
				buf.WriteString(": ")

				if len(node.Subnodes) > 0 {
					nodeClassName := bytcase.ToCamel(node.Name)
					buf.WriteString("Optional[")
					buf.Write(nodeClassName)
					buf.WriteString("]")
				} else {
					buf.WriteString("str = ''")
				}
				buf.WriteString("\n")
			}
		}

		// Generate __str__ method
		buf.WriteString("\n\tdef __str__(self) -> str:\n")

		// Check if prompt has variables
		vars, _ := p.Vars(f.Content, caseconv.CaseSnake)
		if len(vars) > 0 {
			stringTemplateWithClass(&buf, p.Nodes, f.Content)
		} else {
			stringTemplate(&buf, p.Nodes, f.Content)
		}

		if i < len(f.Prompts)-1 {
			buf.WriteString("\n\n")
		}
	}

	_, err := buf.WriteTo(w)
	return err
}

func functionHeader(buf *bytes.Buffer, title []byte, stringVars [][]byte, length int) {
	title = bytcase.ToSnake(title)
	buf.WriteString("def ")
	buf.Write(title)
	buf.WriteRune('(')
	if len(title)+length+10 > cfg.MaxLineLen {
		for i := range stringVars {
			if i == 0 {
				buf.WriteRune('\n')
			}
			buf.WriteRune('\t')
			buf.Write(stringVars[i])
			buf.WriteString(": str,\n")
		}
	} else {
		for i := range stringVars {
			buf.Write(stringVars[i])
			buf.WriteString(": str")
			if i < len(stringVars)-1 {
				buf.WriteString(", ")
			}
		}
	}
	buf.WriteString(") -> str:")
}

func stringTemplate(buf *bytes.Buffer, toks token.Slice, content []byte) {
	buf.WriteString(`		return f"""`)
	for _, t := range toks {
		if t.Kind == kind.Var {
			buf.Write(t.GetWrap(content, '{', '}'))
		} else {
			buf.Write(t.Get(content))
		}
	}
	buf.WriteString(`"""`)
	buf.WriteRune('\n')
}

func stringTemplateWithClass(buf *bytes.Buffer, toks token.Slice, content []byte) {
	buf.WriteString(`		return f"""`)
	for _, t := range toks {
		if t.Kind == kind.Var {
			// Convert dot notation to class field access
			parts := bytes.Split(t.Get(content), []byte{'.'})
			buf.WriteString("{self.")
			for i, part := range parts {
				buf.Write(bytcase.ToSnake(part))
				if i < len(parts)-1 {
					buf.WriteRune('.')
				}
			}
			buf.WriteRune('}')
		} else {
			buf.Write(t.Get(content))
		}
	}
	buf.WriteString(`"""`)
	buf.WriteRune('\n')
}

func stringLiteral(buf *bytes.Buffer, toks token.Slice, content []byte) {
	buf.WriteRune('\n')
	buf.WriteString(`	return """`)
	for _, t := range toks {
		if t.Kind == kind.Var {
			buf.Write(t.GetWrap(content, '{', '}'))
		} else {
			buf.Write(t.Get(content))
		}
	}
	buf.WriteString(`"""`)
	buf.WriteRune('\n')
}
