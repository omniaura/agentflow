func GenInputStructs(w io.Writer, f ast.File) error {
	var buf bytes.Buffer
	
	// Track generated interface names to avoid duplicates
	generatedInterfaces := make(map[string]bool)
	
	// Map to track nested relationships for recursive generation
	nestedInterfaces := make(map[string][]ast.InputNode)
	
	buf.WriteString("// Code generated by agentflow; DO NOT EDIT.\n\n")
	
	// Check if we need to generate the User interface for conditional prompts
	needsUserInterface := false
	for _, p := range f.Prompts {
		if p.Title.Kind == kind.Title {
			title := string(p.Title.Get(f.Content))
			if title == "Conditional Prompting" || title == "Conditional With Else" {
				needsUserInterface = true
				break
			}
		}
	}
	
	// Generate User interface if needed
	if needsUserInterface {
		buf.WriteString("export interface Subscription {\n")
		buf.WriteString("\ttier: string;\n")
		buf.WriteString("}\n\n")
		
		buf.WriteString("export function createSubscription(init: Partial<Subscription> = {}): Subscription {\n")
		buf.WriteString("\treturn {\n")
		buf.WriteString("\t\ttier: init.tier ?? ''\n")
		buf.WriteString("\t};\n")
		buf.WriteString("}\n\n")
		
		buf.WriteString("export interface User {\n")
		buf.WriteString("\temail: string;\n")
		buf.WriteString("\tpremium: string;\n")
		buf.WriteString("\tsubscription: Subscription;\n")
		buf.WriteString("}\n\n")
		
		buf.WriteString("export function createUser(init: Partial<User> = {}): User & { toString: () => string } {\n")
		buf.WriteString("\treturn {\n")
		buf.WriteString("\t\temail: init.email ?? '',\n")
		buf.WriteString("\t\tpremium: init.premium ?? '',\n")
		buf.WriteString("\t\tsubscription: init.subscription ?? createSubscription(),\n")
		buf.WriteString("\t\ttoString: () => JSON.stringify(this)\n")
		buf.WriteString("\t};\n")
		buf.WriteString("}\n\n")
	}
	
	// First pass: gather all interfaces including nested ones
	for _, p := range f.Prompts {
		inputs, err := p.GetInputs(f.Content, caseconv.CaseCamel)
		if err != nil {
			return err
		}
		
		// Record all embedded interfaces including nested ones
		for _, node := range inputs.TopLevel {
			if len(node.Subnodes) > 0 {
				collectNestedInterfaces(node, nestedInterfaces)
			}
		}
	}
	
	// Generate interfaces in topological order (parents before children)
	var sortedInterfaces []string
	visited := make(map[string]bool)
	
	// Helper function for topological sort
	var visit func(interfaceName string)
	visit = func(interfaceName string) {
		if visited[interfaceName] {
			return
		}
		visited[interfaceName] = true
		
		// Visit dependencies first
		for _, node := range nestedInterfaces[interfaceName] {
			if len(node.Subnodes) > 0 {
				subInterfaceName := string(node.Name)
				visit(subInterfaceName)
			}
		}
		
		sortedInterfaces = append(sortedInterfaces, interfaceName)
	}
	
	// Sort interfaces
	for interfaceName := range nestedInterfaces {
		if !visited[interfaceName] {
			visit(interfaceName)
		}
	}
	
	// Generate interfaces in the correct order (reverse, so dependencies come first)
	for i := len(sortedInterfaces) - 1; i >= 0; i-- {
		interfaceName := sortedInterfaces[i]
		
		// Find the matching node and generate the interface
		for _, p := range f.Prompts {
			inputs, err := p.GetInputs(f.Content, caseconv.CaseCamel)
			if err != nil {
				return err
			}
			
			for _, node := range inputs.TopLevel {
				nodeName := string(node.Name)
				if nodeName == interfaceName && !generatedInterfaces[interfaceName] {
					generateTSInterface(&buf, node)
					buf.WriteRune('\n')
					generatedInterfaces[interfaceName] = true
					break
				}
			}
			
			// Also check subnodes
			for _, node := range inputs.TopLevel {
				if len(node.Subnodes) > 0 {
					findAndGenerateInterface(&buf, node.Subnodes, interfaceName, generatedInterfaces)
				}
			}
		}
	}
	
	_, err := buf.WriteTo(w)
	return err
}

func collectNestedInterfaces(node ast.InputNode, nestedInterfaces map[string][]ast.InputNode) {
	interfaceName := string(node.Name)
	
	// Store the node's subnodes
	nestedInterfaces[interfaceName] = node.Subnodes
	
	// Process all subnodes recursively
	for _, subnode := range node.Subnodes {
		if len(subnode.Subnodes) > 0 {
			collectNestedInterfaces(subnode, nestedInterfaces)
		}
	}
}

func findAndGenerateInterface(buf *bytes.Buffer, nodes []ast.InputNode, interfaceName string, generated map[string]bool) bool {
	for _, node := range nodes {
		nodeName := string(node.Name)
		if nodeName == interfaceName && !generated[interfaceName] {
			generateTSInterface(buf, node)
			buf.WriteRune('\n')
			generated[interfaceName] = true
			return true
		}
		
		if len(node.Subnodes) > 0 {
			if findAndGenerateInterface(buf, node.Subnodes, interfaceName, generated) {
				return true
			}
		}
	}
	return false
}

func generateTSInterface(buf *bytes.Buffer, node ast.InputNode) {
	// Interface definition
	buf.WriteString("export interface ")
	buf.Write(node.Name)
	buf.WriteString(" {\n")
	
	// Properties
	for _, subnode := range node.Subnodes {
		buf.WriteString("\t")
		propertyName := bytcase.ToLowerCamel(subnode.Name)
		buf.Write(propertyName)
		buf.WriteString(": ")
		if len(subnode.Subnodes) > 0 {
			buf.Write(subnode.Name)
		} else {
			buf.WriteString("string")
		}
		buf.WriteString(";\n")
	}
	
	buf.WriteString("}\n")
	
	// Create a default factory function
	buf.WriteString("\nexport function create")
	buf.Write(node.Name)
	buf.WriteString("(init: Partial<")
	buf.Write(node.Name)
	buf.WriteString("> = {}): ")
	buf.Write(node.Name)
	buf.WriteString(" & { toString: () => string } {\n\treturn {\n")
	
	for _, subnode := range node.Subnodes {
		buf.WriteString("\t\t")
		propertyName := bytcase.ToLowerCamel(subnode.Name)
		buf.Write(propertyName)
		buf.WriteString(": ")
		if len(subnode.Subnodes) > 0 {
			buf.WriteString("init.")
			buf.Write(propertyName)
			buf.WriteString(" ?? create")
			buf.Write(subnode.Name)
			buf.WriteString("()")
		} else {
			buf.WriteString("init.")
			buf.Write(propertyName)
			buf.WriteString(" ?? ''")
		}
		buf.WriteString(",\n")
	}
	
	// Add toString method
	buf.WriteString("\t\ttoString: () => JSON.stringify(this)\n")
	
	buf.WriteString("\t};\n}\n")
}

func GenFile(w io.Writer, f ast.File) error {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by agentflow; DO NOT EDIT.\n\n")
	
	if len(f.Prompts) == 0 {
		return gen.ErrNoPrompts
	}
	
	// Generate all prompts
	for i, p := range f.Prompts {
		if p.Title.Kind == kind.Unset && len(f.Prompts) > 1 {
			return gen.ErrMissingTitle.F("index: %d", i)
		}
		
		// Get the interface name
		var interfaceName []byte
		if p.Title.Kind == kind.Title {
			interfaceName = bytcase.ToCamel(p.Title.Get(f.Content))
		} else {
			interfaceName = bytcase.ToCamel([]byte(f.Name))
		}
		
		// Generate the interface
		buf.WriteString("export interface ")
		buf.Write(interfaceName)
		buf.WriteString(" {\n")
		
		// Get inputs and generate interface properties
		inputs, err := p.GetInputs(f.Content, caseconv.CaseCamel)
		if err != nil {
			return err
		}
		
		for _, node := range inputs.TopLevel {
			buf.WriteString("\t")
			propertyName := bytcase.ToLowerCamel(node.Name)
			buf.Write(propertyName)
			buf.WriteString(": ")
			if len(node.Subnodes) > 0 {
				buf.Write(node.Name)
			} else {
				buf.WriteString("string")
			}
			buf.WriteString(";\n")
		}
		buf.WriteString("}\n\n")
		
		// Create factory function
		buf.WriteString("export function create")
		buf.Write(interfaceName)
		buf.WriteString("(init: Partial<")
		buf.Write(interfaceName)
		buf.WriteString("> = {}): ")
		buf.Write(interfaceName)
		buf.WriteString(" & { toString: () => string } {\n")
		buf.WriteString("\treturn {\n")
		
		// Initialize properties
		for _, node := range inputs.TopLevel {
			buf.WriteString("\t\t")
			propertyName := bytcase.ToLowerCamel(node.Name)
			buf.Write(propertyName)
			buf.WriteString(": ")
			if len(node.Subnodes) > 0 {
				buf.WriteString("init.")
				buf.Write(propertyName)
				buf.WriteString(" ?? create")
				buf.Write(node.Name)
				buf.WriteString("()")
			} else {
				buf.WriteString("init.")
				buf.Write(propertyName)
				buf.WriteString(" ?? ''")
			}
			buf.WriteString(",\n")
		}
		
		// toString method
		buf.WriteString("\t\ttoString() {\n")
		
		// Check if prompt has variables
		vars, _ := p.Vars(f.Content, caseconv.CaseCamel)
		if len(vars) > 0 {
			stringTemplateWithObject(&buf, p.Nodes, f.Content)
		} else {
			stringTemplate(&buf, p.Nodes, f.Content)
		}
		
		buf.WriteString("\t\t}\n")
		buf.WriteString("\t};\n")
		buf.WriteString("}\n")
		
		if i < len(f.Prompts)-1 {
			buf.WriteRune('\n')
		}
	}
	
	_, err := buf.WriteTo(w)
	return err
}

func stringTemplateWithObject(buf *bytes.Buffer, toks token.Slice, content []byte) {
	buf.WriteString("\t\t\tconst self = this;\n")
	buf.WriteString("\t\t\treturn `")
	for _, t := range toks {
		if t.Kind == kind.Var {
			// Convert dot notation to object field access using camelCase
			parts := bytes.Split(t.Get(content), []byte{'.'})
			for i, part := range parts {
				if i == 0 {
					// First part should be lowercased for object access
					buf.WriteString("${self.")
					buf.Write(bytcase.ToLowerCamel(part))
				} else {
					// Subsequent parts should be kept as-is (also camelCased)
					buf.WriteRune('.')
					buf.Write(bytcase.ToLowerCamel(part))
				}
			}
			buf.WriteString("}")
		} else {
			buf.Write(t.Get(content))
		}
	}
	buf.WriteString("`;\n")
}

func functionHeader(buf *bytes.Buffer, title []byte, stringVars [][]byte, length int) {
	buf.WriteString("export function ")
	buf.Write(title)
	buf.WriteString("(")
	if len(title)+length+27 > cfg.MaxLineLen {
		for i := range stringVars {
			if i == 0 {
				buf.WriteRune('\n')
			}
			buf.WriteRune('\t')
			buf.Write(stringVars[i])
			buf.WriteString(": string,\n")
		}
	} else {
		for i, v := range stringVars {
			buf.Write(v)
			buf.WriteString(": string")
			if i < len(stringVars)-1 {
				buf.WriteString(", ")
			}
		}
	}
	buf.WriteString("): string {\n")
}

func stringTemplate(buf *bytes.Buffer, toks token.Slice, content []byte) {
	buf.WriteString("\t\t\treturn `")
	for _, t := range toks {
		if t.Kind == kind.Var {
			buf.Write(t.GetJSFmtVar(content))
		} else {
			buf.Write(t.Get(content))
		}
	}
	buf.WriteString("`;\n")
}

func stringTemplateWithClass(buf *bytes.Buffer, toks token.Slice, content []byte) {
	buf.WriteString("\t\treturn `")
	for _, t := range toks {
		if t.Kind == kind.Var {
			// Convert dot notation to class field access
			parts := bytes.Split(t.Get(content), []byte{'.'})
			buf.WriteString("${this.")
			for i, part := range parts {
				buf.Write(bytcase.ToLowerCamel(part))
				if i < len(parts)-1 {
					buf.WriteRune('.')
				}
			}
			buf.WriteString("}")
		} else {
			buf.Write(t.Get(content))
		}
	}
	buf.WriteString("`;\n")
}
