package check

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestCheckInlineSQL(t *testing.T) {
	root := t.TempDir()
	write := func(name, body string) {
		path := filepath.Join(root, name)
		os.MkdirAll(filepath.Dir(path), 0o755)
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", "module example.com/m\n")
	write("sqlc.yaml", "version: \"2\"\nsql:\n  - queries: [api/api_af.sql]\n    gen:\n      go: {package: db, out: db}\n")
	write("db/q.go", "package db\n\nimport \"context\"\n\nconst getX = `-- name: GetX :one\nSELECT 1`\n\ntype Queries struct{}\n\nfunc (q *Queries) GetX(ctx context.Context) (int64, error) { return 0, nil }\n")
	write("api/api.af", ".route GET /x GetX\n.public\n.sql :one\nSELECT 1\n")

	findings := func() map[string]string {
		report, err := Run([]string{root + "/..."}, true)
		if err != nil {
			t.Fatal(err)
		}
		out := map[string]string{}
		for _, f := range report.Findings {
			out[filepath.Base(f.File)+" "+f.Kind] = f.Message
		}
		return out
	}
	if got := findings(); !strings.Contains(got["api_af.sql missing"], "generated queries are missing") {
		t.Fatalf("findings = %v", got)
	}
	write("api/api_af.sql", "-- Code generated by agentflow from api.af; DO NOT EDIT.\n\n-- name: GetX :one\nSELECT 2;\n")
	if got := findings(); !strings.Contains(got["api_af.sql drift"], "generated queries are out of date") {
		t.Fatalf("findings = %v", got)
	}
	write("api/api_af.sql", "-- Code generated by agentflow from api.af; DO NOT EDIT.\n\n-- name: GetX :one\nSELECT 1;\n")
	if got := findings(); got["api_af.sql drift"] != "" || got["api_af.sql missing"] != "" {
		t.Fatalf("findings = %v", got)
	}
}
