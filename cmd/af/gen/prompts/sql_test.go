func TestRenderSQL(t *testing.T) {
	f, err := ast.NewFile("notes.af", []byte(".route POST /notes CreateNote\n.sql :one\nINSERT INTO notes (body) VALUES (@body) RETURNING *\n\n.route GET /notes ListNotes\n\n.route DELETE /notes/{id} DeleteNote\n.sql :execrows\nDELETE FROM notes WHERE id = @id;\n"))
	if err != nil {
		t.Fatal(err)
	}
	want := "-- Code generated by agentflow from notes.af; DO NOT EDIT.\n\n-- name: CreateNote :one\nINSERT INTO notes (body) VALUES (@body) RETURNING *;\n\n-- name: DeleteNote :execrows\nDELETE FROM notes WHERE id = @id;\n"
	if got := string(RenderSQL(f)); got != want {
		t.Fatalf("got\n%s\nwant\n%s", got, want)
	}
	f, _ = ast.NewFile("x.af", []byte(".route GET /x X\n"))
	if RenderSQL(f) != nil {
		t.Fatal("a file without .sql renders queries")
	}
}

// writeModule writes a module whose sqlc config may or may not read the
// .af file's _af.sql, with sqlc output for GetX.
func writeModule(t *testing.T, queries string) string {
	t.Helper()
	root := t.TempDir()
	files := map[string]string{
		"go.mod":    "module example.com/m\n",
		"sqlc.yaml": "version: \"2\"\nsql:\n  - queries: [" + queries + "]\n    gen:\n      go: {package: db, out: db, sql_package: pgx/v5}\n",
		"db/q.go":   "package db\n\nimport \"context\"\n\nconst getX = `-- name: GetX :one\nSELECT 1`\n\ntype Queries struct{}\n\nfunc (q *Queries) GetX(ctx context.Context, id int64) (int64, error) { return 0, nil }\n",
	}
	for name, body := range files {
		path := filepath.Join(root, name)
		os.MkdirAll(filepath.Dir(path), 0o755)
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	sqlcgo.ResetCache()
	return root
}

func TestRenderChecksInlineSQL(t *testing.T) {
	for _, tt := range []struct{ name, queries, src, msg string }{
		{"not read by sqlc", "other.sql", ".route GET /x/{id} GetX\n.sql :one\nSELECT 1\n", "no sqlc config reads"},
		{"not generated yet", "api/api_af.sql", ".route GET /x/{id} GetY\n.sql :one\nSELECT 1\n", "sqlc has not generated query GetY from api_af.sql yet"},
		{"stale kind", "api/api_af.sql", ".route GET /x/{id} GetX\n.sql :many\nSELECT 1\n", "sqlc generated GetX as :one, not :many"},
		{"ok", "api", ".route GET /x/{id} GetX\n.public\n.sql :one\nSELECT 1\n", ""},
		// A route query named like a tool's: reported at the second .sql.
		{"duplicate", "api", ".route GET /x/{id} GetXTool\n.sql :one\nSELECT 1\n\n.tool get_x\nGets x.\n.sql :one\nSELECT 1\n", "query GetXTool is written twice in api.af"},
	} {
		t.Run(tt.name, func(t *testing.T) {
			root := writeModule(t, tt.queries)
			os.MkdirAll(filepath.Join(root, "api"), 0o755)
			name := filepath.Join(root, "api", "api.af")
			_, code, err := Render(name, []byte(tt.src))
			if tt.msg == "" {
				if err != nil || !bytes.Contains(code, []byte("rt.Queries.GetX(r.Context(), arg)")) {
					t.Fatalf("got %v\n%s", err, code)
				}
				return
			}
			if err == nil || !strings.Contains(err.Error(), tt.msg) {
				t.Fatalf("got %v, want %q", err, tt.msg)
			}
			// The error points at the .sql line.
			line := "api.af:2:1:"
			if tt.name == "duplicate" {
				line = "api.af:7:1:"
			}
			if msgs := Diagnose(name, []byte(tt.src), err); !strings.Contains(msgs[0], line) {
				t.Fatalf("diagnostic %q", msgs[0])
			}
		})
	}
}

func TestRenderResolvesSQLCFiles(t *testing.T) {
	one, two := "-- name: GetX :one\nSELECT @id::bigint;\n", "-- name: GetY :one\nSELECT 1;\n\n-- name: GetX :one\nSELECT @id::bigint;\n"
	for _, tt := range []struct{ name, queries, file, src, msg string }{
		{"only query", "q", one, ".tool load\n.sqlc ../q/x.sql\nLoads x.\n", ""},
		{"block comment", "q", "/* name: GetX :one */\nSELECT @id::bigint;\n", ".tool load\n.sqlc ../q/x.sql\nLoads x.\n", ""},
		{"named", "q/x.sql", two, ".tool load\n.sqlc ../q/x.sql GetX\nLoads x.\n", ""},
		{"after the tool", "q", two, ".tool get_x\n.sqlc ../q/x.sql\nLoads x.\n", ""},
		{"query name alone", "q", two, ".tool load\n.sqlc GetX\nLoads x.\n", ""},
		{"several", "q", two, ".tool load\n.sqlc ../q/x.sql\nLoads x.\n", "../q/x.sql has several queries (GetY, GetX): name one, as in .sqlc ../q/x.sql GetY"},
		{"not in the file", "q", one, ".tool load\n.sqlc ../q/x.sql GetZ\nLoads x.\n", "../q/x.sql has no query GetZ; it has GetX"},
		{"not read by sqlc", "other.sql", one, ".tool load\n.sqlc ../q/x.sql\nLoads x.\n", "no sqlc config reads ../q/x.sql: add it to the queries of"},
		{"not generated yet", "q", "-- name: GetZ :one\nSELECT 1;\n", ".tool load\n.sqlc ../q/x.sql\nLoads x.\n", "sqlc has not generated query GetZ from ../q/x.sql yet"},
		{"no queries", "q", "SELECT 1;\n", ".tool load\n.sqlc ../q/x.sql\nLoads x.\n", "declares no sqlc queries"},
		{"missing file", "q", one, ".tool load\n.sqlc ../q/nope.sql\nLoads x.\n", "no such file"},
	} {
		t.Run(tt.name, func(t *testing.T) {
			root := writeModule(t, tt.queries)
			os.MkdirAll(filepath.Join(root, "api"), 0o755)
			os.MkdirAll(filepath.Join(root, "q"), 0o755)
			os.WriteFile(filepath.Join(root, "q", "x.sql"), []byte(tt.file), 0o644)
			name := filepath.Join(root, "api", "api.af")
			_, code, err := Render(name, []byte(tt.src))
			if tt.msg == "" {
				if err != nil || !bytes.Contains(code, []byte("t.Queries.GetX(ctx, arg)")) {
					t.Fatalf("got %v\n%s", err, code)
				}
				return
			}
			if err == nil || !strings.Contains(err.Error(), tt.msg) {
				t.Fatalf("got %v, want %q", err, tt.msg)
			}
			if msgs := Diagnose(name, []byte(tt.src), err); !strings.Contains(msgs[0], "api.af:2:1:") {
				t.Fatalf("diagnostic %q", msgs[0])
			}
		})
	}
}

func TestGenerateSQLRunsSqlc(t *testing.T) {
	root := writeModule(t, "api/api_af.sql")
	name := filepath.Join(root, "api", "api.af")
	os.MkdirAll(filepath.Dir(name), 0o755)
	os.WriteFile(name, []byte(".route GET /x/{id} GetX\n.public\n.sql :one\nSELECT @id::bigint\n"), 0o644)

	// A fake sqlc records how it was run.
	bin := t.TempDir()
	log := filepath.Join(bin, "log")
	os.WriteFile(filepath.Join(bin, "sqlc"), []byte("#!/bin/sh\necho \"$PWD $@\" >> "+log+"\n"), 0o755)
	t.Setenv("PATH", bin+string(os.PathListSeparator)+os.Getenv("PATH"))

	var out bytes.Buffer
	if err := generate([]string{name}, &out); err != nil {
		t.Fatalf("%v\n%s", err, out.String())
	}
	if b, _ := os.ReadFile(SQLPath(name)); !strings.Contains(string(b), "-- name: GetX :one\nSELECT @id::bigint;") {
		t.Fatalf("_af.sql = %s", b)
	}
	if b, _ := os.ReadFile(log); strings.TrimSpace(string(b)) != root+" generate -f sqlc.yaml" {
		t.Fatalf("sqlc ran as %q", b)
	}
	if _, err := os.Stat(OutputPath(name)); err != nil {
		t.Fatal("no _af.go:", err)
	}

	// Unchanged queries don't rerun sqlc.
	if err := generate([]string{name}, &out); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(log); strings.Count(string(b), "generate") != 1 {
		t.Fatalf("sqlc reran: %q", b)
	}

	// --sqlc=never only says what to run.
	Sqlc = "never"
	t.Cleanup(func() { Sqlc = "auto" })
	os.WriteFile(name, []byte(".route GET /x/{id} GetX\n.public\n.sql :one\nSELECT @id::bigint + 0\n"), 0o644)
	out.Reset()
	generate([]string{name}, &out)
	if !strings.Contains(out.String(), "queries changed: run sqlc generate for "+filepath.Join(root, "sqlc.yaml")) {
		t.Fatalf("output %q", out.String())
	}

	// Dropping the last .sql removes the generated queries file.
	os.WriteFile(name, []byte(".route GET /x/{id} GetX\n.public\n"), 0o644)
	generate([]string{name}, &out)
	if _, err := os.Stat(SQLPath(name)); !os.IsNotExist(err) {
		t.Fatal("_af.sql was not removed")
	}
}

// Following af gen's advice to add the _af.sql to sqlc.yaml leaves the
// file unchanged, but sqlc still has to generate its queries.
func TestGenerateSQLRunsSqlcForUngeneratedQueries(t *testing.T) {
	root := writeModule(t, "other.sql")
	name := filepath.Join(root, "api", "api.af")
	os.MkdirAll(filepath.Dir(name), 0o755)
	os.WriteFile(name, []byte(".route GET /x/{id} GetY\n.public\n.sql :one\nSELECT @id::bigint\n"), 0o644)
	bin := t.TempDir()
	log := filepath.Join(bin, "log")
	os.WriteFile(filepath.Join(bin, "sqlc"), []byte("#!/bin/sh\necho \"$PWD $@\" >> "+log+"\n"), 0o755)
	t.Setenv("PATH", bin+string(os.PathListSeparator)+os.Getenv("PATH"))

	var out bytes.Buffer
	if err := generate([]string{name}, &out); err == nil {
		t.Fatal("generated a route whose query no sqlc config reads")
	}
	if _, err := os.Stat(log); err == nil {
		t.Fatal("sqlc ran for a file no config reads")
	}
	os.WriteFile(filepath.Join(root, "sqlc.yaml"), []byte("version: \"2\"\nsql:\n  - queries: [api/api_af.sql]\n    gen:\n      go: {package: db, out: db, sql_package: pgx/v5}\n"), 0o644)
	sqlcgo.ResetCache()
	// The fake sqlc generates nothing, so GetY is still missing after it.
	generate([]string{name}, &out)
	if b, _ := os.ReadFile(log); strings.TrimSpace(string(b)) != root+" generate -f sqlc.yaml" {
		t.Fatalf("sqlc ran as %q", b)
	}
}

func TestRenderChecksMapFuncs(t *testing.T) {
	src := ".route GET /x/{id} db.GetX\n.public\n.map xCard\n"
	for _, tt := range []struct{ name, goSrc, msg string }{
		{"func", "func xCard(n int64) string { return \"\" }", ""},
		{"var", "var xCard = func(n int64) string { return \"\" }", ""},
		{"missing", "func other() {}", "package api declares no func xCard"},
		// A method is not callable by name; nor is a func only tests see.
		{"method", "type T struct{}\n\nfunc (T) xCard(n int64) string { return \"\" }", "declares no func xCard"},
		{"typed var", "var xCard func(int64) string", ""},
		{"not a func", "var xCard int", "xCard must be a func taking the query's row"},
		// Vars the compiler may accept are left to it.
		{"var of another func", "var xCard = other\n\nfunc other(n int64) string { return \"\" }", ""},
		{"var of a named func type", "type mapper func(int64) string\n\nvar xCard mapper = func(n int64) string { return \"\" }", ""},
		{"var of a literal", "var xCard = 3", "xCard must be a func"},
		// Local named types resolve, through chains, wherever they're declared.
		{"var of a named int", "var xCard mapper\n\ntype mapper int", "xCard must be a func"},
		{"var of a named struct", "type mapper struct{}\n\nvar xCard mapper", "xCard must be a func"},
		{"var of a type chain", "type m1 m2\n\ntype m2 func(int64) string\n\nvar xCard m1", ""},
		{"var of a named two-result func", "type mapper func(int64) (string, error)\n\nvar xCard mapper", "xCard must be a func"},
		{"var of a type cycle", "type a b\n\ntype b a\n\nvar xCard a", ""},
		{"var of a map", "var xCard map[int64]string", "xCard must be a func"},
		{"no result", "func xCard(n int64) {}", "xCard must be a func"},
		{"two params", "func xCard(a, b int64) string { return \"\" }", "xCard must be a func"},
		{"two results", "func xCard(n int64) (string, error) { return \"\", nil }", "xCard must be a func"},
		// A file the build leaves out declares nothing.
		{"build tag", "//go:build never\n\npackage api\n\nfunc xCard(n int64) string { return \"\" }", "declares no func xCard"},
	} {
		t.Run(tt.name, func(t *testing.T) {
			root := writeModule(t, "db")
			dir := filepath.Join(root, "api")
			os.MkdirAll(dir, 0o755)
			goSrc := "package api\n\n" + tt.goSrc
			if strings.HasPrefix(tt.goSrc, "//go:build") {
				goSrc = tt.goSrc
			}
			os.WriteFile(filepath.Join(dir, "cards.go"), []byte(goSrc+"\n"), 0o644)
			os.WriteFile(filepath.Join(dir, "cards_test.go"), []byte("package api\n\nfunc xCard(n int64) string { return \"\" }\n"), 0o644)
			// A stale generated file doesn't count either.
			os.WriteFile(filepath.Join(dir, "api_af.go"), []byte("package api\n\nfunc xCard(n int64) string { return \"\" }\n"), 0o644)
			name := filepath.Join(dir, "api.af")
			_, code, err := Render(name, []byte(src))
			if tt.msg == "" {
				if err != nil || !bytes.Contains(code, []byte("afhttp.WriteJSON(w, r, http.StatusOK, xCard(row))")) {
					t.Fatalf("got %v\n%s", err, code)
				}
				return
			}
			if err == nil || !strings.Contains(err.Error(), tt.msg) {
				t.Fatalf("got %v, want %q", err, tt.msg)
			}
			// The error points at the .map line.
			if msgs := Diagnose(name, []byte(src), err); !strings.Contains(msgs[0], "api.af:3:1:") {
				t.Fatalf("diagnostic %q", msgs[0])
			}
		})
	}
}

func TestRenderSwag(t *testing.T) {
	src := ".route GET /x/{id} db.GetX\n"
	for _, tt := range []struct {
		name  string
		swag  bool
		files map[string]string
		want  string // the @Security line, "" for none, "-" for no annotations
	}{
		{"no swag", false, map[string]string{"api/info.go": "// @securityDefinitions.apikey BearerAuth\npackage api\n"}, "-"},
		{"nearest definition", true, map[string]string{
			"info.go":     "// @securityDefinitions.apikey RootKey\npackage m\n",
			"api/info.go": "// @securityDefinitions.apikey BearerAuth\npackage api\n",
		}, "BearerAuth"},
		{"ancestor", true, map[string]string{"info.go": "// @securityDefinitions.apikey RootKey\npackage m\n"}, "RootKey"},
		{"the module's only one", true, map[string]string{"admin/info.go": "// @securityDefinitions.apikey AdminKey\npackage admin\n"}, "AdminKey"},
		{"ambiguous", true, map[string]string{
			"admin/info.go": "// @securityDefinitions.apikey AdminKey\npackage admin\n",
			"v5/info.go":    "// @securityDefinitions.apikey BearerAuth\npackage v5\n",
		}, ""},
	} {
		t.Run(tt.name, func(t *testing.T) {
			root := writeModule(t, "db")
			if tt.swag {
				os.WriteFile(filepath.Join(root, "go.mod"), []byte("module example.com/m\n\nrequire github.com/swaggo/swag v1.16.6\n"), 0o644)
			}
			for name, body := range tt.files {
				os.MkdirAll(filepath.Dir(filepath.Join(root, name)), 0o755)
				os.WriteFile(filepath.Join(root, name), []byte(body), 0o644)
			}
			os.MkdirAll(filepath.Join(root, "api"), 0o755)
			_, code, err := Render(filepath.Join(root, "api", "items.af"), []byte(src))
			if err != nil {
				t.Fatal(err)
			}
			switch {
			case tt.want == "-":
				if bytes.Contains(code, []byte("@Router")) {
					t.Fatalf("annotated without swag:\n%s", code)
				}
			case tt.want == "":
				if !bytes.Contains(code, []byte("// @Tags items\n")) || bytes.Contains(code, []byte("@Security")) {
					t.Fatalf("want no @Security:\n%s", code)
				}
			default:
				if !bytes.Contains(code, []byte("// @Tags items\n// @Security "+tt.want+"\n")) || !bytes.Contains(code, []byte("// @Router /x/{id} [get]")) {
					t.Fatalf("want @Security %s:\n%s", tt.want, code)
				}
			}
		})
	}
}
