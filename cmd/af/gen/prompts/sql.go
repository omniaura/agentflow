package prompts

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"log/slog"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"

	"github.com/omniaura/agentflow/pkg/ast"
	"github.com/omniaura/agentflow/pkg/gen/gogen"
	"github.com/omniaura/agentflow/pkg/sqlcgo"
)

// Sqlc is when af gen runs sqlc generate after writing queries: "auto" runs
// it when a query changed and sqlc is on PATH, "never" leaves it to you.
var Sqlc = "auto"

// SQLPath returns the _af.sql path generated for the .af file name.
func SQLPath(name string) string {
	return strings.TrimSuffix(name, ".af") + "_af.sql"
}

// RenderSQL returns the sqlc queries file for f: one query per route that
// writes its SQL with .sql. It returns nil when no route does.
func RenderSQL(f ast.File) []byte {
	var b bytes.Buffer
	for _, r := range f.Routes {
		if r.SQL == "" {
			continue
		}
		if b.Len() == 0 {
			fmt.Fprintf(&b, "-- Code generated by agentflow from %s.af; DO NOT EDIT.\n", f.Name)
		}
		fmt.Fprintf(&b, "\n-- name: %s %s\n%s", r.Query, r.SQLKind, r.SQL)
		if !strings.HasSuffix(r.SQL, ";") {
			b.WriteByte(';')
		}
		b.WriteByte('\n')
	}
	if b.Len() == 0 {
		return nil
	}
	return b.Bytes()
}

// sqlPackage returns the sqlc package whose config reads the _af.sql of
// the .af file name, or an error saying how to add it.
func sqlPackage(name string, repo *sqlcgo.Repo) (*sqlcgo.Package, error) {
	path := SQLPath(name)
	for _, p := range repo.Packages {
		if p.ReadsQueryFile(path) {
			return p, nil
		}
	}
	var configs []string
	for _, p := range repo.Packages {
		if !slices.Contains(configs, p.Config) {
			configs = append(configs, p.Config)
		}
	}
	return nil, fmt.Errorf("no sqlc config reads %s: add it to the queries of %s", path, strings.Join(configs, " or "))
}

// checkSQLRoutes reports routes whose inline queries sqlc cannot see or
// has not generated yet, at their .sql line.
func checkSQLRoutes(name string, f ast.File, repo *sqlcgo.Repo) error {
	var pkg *sqlcgo.Package
	for _, r := range f.Routes {
		if r.SQL == "" {
			continue
		}
		if pkg == nil {
			p, err := sqlPackage(name, repo)
			if err != nil {
				return &gogen.RouteError{Offset: r.SQLOffset, Err: err}
			}
			pkg = p
		}
		q, ok := pkg.Queries[r.Query]
		switch {
		case !ok:
			return &gogen.RouteError{Offset: r.SQLOffset, Err: fmt.Errorf("sqlc has not generated query %s from %s yet: run sqlc generate, then af gen", r.Query, filepath.Base(SQLPath(name)))}
		case string(q.Kind) != r.SQLKind:
			return &gogen.RouteError{Offset: r.SQLOffset, Err: fmt.Errorf("sqlc generated %s as %s, not %s: run sqlc generate, then af gen", r.Query, q.Kind, r.SQLKind)}
		}
	}
	return nil
}

// generateSQL writes the _af.sql of every file with inline queries, then
// runs sqlc generate for each config whose queries changed. Files that do
// not parse are left to the Go pass to report.
func generateSQL(files []string, out io.Writer) error {
	var configs []string
	for _, name := range files {
		src, err := os.ReadFile(name)
		if err != nil {
			continue
		}
		f, err := ast.NewFile(filepath.Base(name), src)
		if err != nil {
			continue
		}
		sql := RenderSQL(f)
		path := SQLPath(name)
		if sql == nil {
			// A file that no longer writes queries drops its _af.sql.
			if b, err := os.ReadFile(path); err == nil && bytes.HasPrefix(b, []byte("-- Code generated by agentflow")) {
				if err := os.Remove(path); err != nil {
					return err
				}
			}
			continue
		}
		changed, err := writeFileAtomic(path, sql)
		if err != nil {
			return err
		}
		if !changed {
			continue
		}
		slog.Info("Generated", "file", path)
		repo, err := sqlcgo.Find(filepath.Dir(name))
		if err != nil {
			continue
		}
		if p, err := sqlPackage(name, repo); err == nil && !slices.Contains(configs, p.Config) {
			configs = append(configs, p.Config)
		}
	}
	if len(configs) == 0 {
		return nil
	}
	if Sqlc == "never" {
		fmt.Fprintf(out, "queries changed: run sqlc generate for %s, then af gen\n", strings.Join(configs, ", "))
		return nil
	}
	bin, err := exec.LookPath("sqlc")
	if err != nil {
		fmt.Fprintf(out, "queries changed, but sqlc is not on PATH: run sqlc generate for %s, then af gen\n", strings.Join(configs, ", "))
		return nil
	}
	for _, config := range configs {
		cmd := exec.Command(bin, "generate", "-f", filepath.Base(config))
		cmd.Dir = filepath.Dir(config)
		var stderr bytes.Buffer
		cmd.Stdout, cmd.Stderr = out, &stderr
		if err := cmd.Run(); err != nil {
			return errors.New("sqlc generate -f " + config + ": " + strings.TrimSpace(stderr.String()))
		}
		slog.Info("Ran sqlc generate", "config", config)
	}
	sqlcgo.ResetCache()
	return nil
}
