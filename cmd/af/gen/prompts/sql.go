// Sqlc is when af gen runs sqlc generate after writing queries: "auto" runs
// it when a query changed and sqlc is on PATH, "never" leaves it to you.
var Sqlc = "auto"

// SQLPath returns the _af.sql path generated for the .af file name.
func SQLPath(name string) string {
	return strings.TrimSuffix(name, ".af") + "_af.sql"
}

// sqlQuery is a query written in an .af file: a route's or a tool's.
type sqlQuery struct {
	name, kind, sql string
	offset          int
}

// sqlQueries returns the queries f writes with .sql, routes first.
func sqlQueries(f ast.File) []sqlQuery {
	var qs []sqlQuery
	for _, r := range f.Routes {
		if r.SQL != "" {
			qs = append(qs, sqlQuery{r.Query, r.SQLKind, r.SQL, r.SQLOffset})
		}
	}
	for _, t := range f.Tools {
		if t.SQL != "" {
			qs = append(qs, sqlQuery{gogen.ToolQuery(t), t.SQLKind, t.SQL, t.SQLOffset})
		}
	}
	return qs
}

// duplicateQuery reports a query name f's routes and tools use twice,
// which sqlc would reject, at the second one's .sql line.
func duplicateQuery(f ast.File) error {
	seen := map[string]bool{}
	for _, q := range sqlQueries(f) {
		if seen[q.name] {
			return &gogen.RouteError{Offset: q.offset, Err: fmt.Errorf("query %s is written twice in %s.af; tool queries are named after the tool plus Tool, so rename the tool or the route's query", q.name, f.Name)}
		}
		seen[q.name] = true
	}
	return nil
}

// RenderSQL returns the sqlc queries file for f: one query per route or
// tool that writes its SQL with .sql. It returns nil when none does.
func RenderSQL(f ast.File) []byte {
	var b bytes.Buffer
	for _, q := range sqlQueries(f) {
		if b.Len() == 0 {
			fmt.Fprintf(&b, "-- Code generated by agentflow from %s.af; DO NOT EDIT.\n", f.Name)
		}
		fmt.Fprintf(&b, "\n-- name: %s %s\n%s", q.name, q.kind, q.sql)
		if !strings.HasSuffix(q.sql, ";") {
			b.WriteByte(';')
		}
		b.WriteByte('\n')
	}
	if b.Len() == 0 {
		return nil
	}
	return b.Bytes()
}

// sqlPackage returns the sqlc package whose config reads the _af.sql of
// the .af file name, or an error saying how to add it.
func sqlPackage(name string, repo *sqlcgo.Repo) (*sqlcgo.Package, error) {
	path := SQLPath(name)
	for _, p := range repo.Packages {
		if p.ReadsQueryFile(path) {
			return p, nil
		}
	}
	var configs []string
	for _, p := range repo.Packages {
		if !slices.Contains(configs, p.Config) {
			configs = append(configs, p.Config)
		}
	}
	return nil, fmt.Errorf("no sqlc config reads %s: add it to the queries of %s", path, strings.Join(configs, " or "))
}

// resolveSQLC names the query each .sqlc file line links, checking that a
// sqlc config reads the file and has generated the query, and pins it to
// that package in pinned. A file's query is the one named on the line,
// the file's only query, or the one named after the tool.
func resolveSQLC(name string, f ast.File, repo *sqlcgo.Repo, pinned map[string]*sqlcgo.Package) error {
	for _, t := range f.Tools {
		if t.SQLCFile == "" {
			continue
		}
		fail := func(format string, a ...any) error {
			return &gogen.DeclError{Offset: t.SQLOffset, Err: fmt.Errorf(format, a...)}
		}
		path := t.SQLCFile
		if !filepath.IsAbs(path) {
			path = filepath.Join(filepath.Dir(name), path)
		}
		src, err := os.ReadFile(path)
		if err != nil {
			return fail(".sqlc: %w", err)
		}
		decls := sqlcgo.QueryDecls(src)
		if len(decls) == 0 {
			return fail(".sqlc: %s declares no sqlc queries (-- name: ListNotes :many)", t.SQLCFile)
		}
		var names []string
		for _, d := range decls {
			names = append(names, d.Name)
		}
		var pkg *sqlcgo.Package
		for _, p := range repo.Packages {
			if p.ReadsQueryFile(path) {
				pkg = p
				break
			}
		}
		if pkg == nil {
			var configs []string
			for _, p := range repo.Packages {
				if !slices.Contains(configs, p.Config) {
					configs = append(configs, p.Config)
				}
			}
			return fail("no sqlc config reads %s: add it to the queries of %s", t.SQLCFile, strings.Join(configs, " or "))
		}
		query := t.SQLCQuery
		switch {
		case query != "":
			if !slices.Contains(names, query) {
				return fail(".sqlc: %s has no query %s; it has %s", t.SQLCFile, query, strings.Join(names, ", "))
			}
		case len(names) == 1:
			query = names[0]
		case slices.Contains(names, gogen.Camel(t.Name)):
			query = gogen.Camel(t.Name)
		default:
			return fail(".sqlc: %s has several queries (%s): name one, as in .sqlc %s %s", t.SQLCFile, strings.Join(names, ", "), t.SQLCFile, names[0])
		}
		if _, ok := pkg.Queries[query]; !ok {
			if pkg.LoadErr != nil {
				return fail("%w", pkg.LoadErr)
			}
			return fail("sqlc has not generated query %s from %s yet: run sqlc generate, then af gen", query, t.SQLCFile)
		}
		t.SQLCQuery = pkg.Name + "." + query
		pinned[t.SQLCQuery] = pkg
	}
	return nil
}

// checkSQLRoutes reports routes and tools whose inline queries sqlc cannot
// see or has not generated yet, at their .sql line.
func checkSQLRoutes(name string, f ast.File, repo *sqlcgo.Repo) error {
	if err := duplicateQuery(f); err != nil {
		return err
	}
	var pkg *sqlcgo.Package
	for _, sq := range sqlQueries(f) {
		if pkg == nil {
			p, err := sqlPackage(name, repo)
			if err != nil {
				return &gogen.RouteError{Offset: sq.offset, Err: err}
			}
			pkg = p
		}
		q, ok := pkg.Queries[sq.name]
		switch {
		case !ok:
			return &gogen.RouteError{Offset: sq.offset, Err: fmt.Errorf("sqlc has not generated query %s from %s yet: run sqlc generate, then af gen", sq.name, filepath.Base(SQLPath(name)))}
		case string(q.Kind) != sq.kind:
			return &gogen.RouteError{Offset: sq.offset, Err: fmt.Errorf("sqlc generated %s as %s, not %s: run sqlc generate, then af gen", sq.name, q.Kind, sq.kind)}
		}
	}
	return nil
}

// generateSQL writes the _af.sql of every file with inline queries, then
// runs sqlc generate for each config whose queries changed. Files that do
// not parse are left to the Go pass to report.
func generateSQL(files []string, out io.Writer) error {
	var configs []string
	for _, name := range files {
		src, err := os.ReadFile(name)
		if err != nil {
			continue
		}
		f, err := ast.NewFile(filepath.Base(name), src)
		if err != nil || duplicateQuery(f) != nil {
			// The Go pass reports it, at the line.
			continue
		}
		sql := RenderSQL(f)
		path := SQLPath(name)
		if sql == nil {
			// A file that no longer writes queries drops its _af.sql.
			if b, err := os.ReadFile(path); err == nil && bytes.HasPrefix(b, []byte("-- Code generated by agentflow")) {
				if err := os.Remove(path); err != nil {
					return err
				}
			}
			continue
		}
		changed, err := writeFileAtomic(path, sql)
		if err != nil {
			return err
		}
		if !changed {
			continue
		}
		slog.Info("Generated", "file", path)
		repo, err := sqlcgo.Find(filepath.Dir(name))
		if err != nil {
			continue
		}
		if p, err := sqlPackage(name, repo); err == nil && !slices.Contains(configs, p.Config) {
			configs = append(configs, p.Config)
		}
	}
	if len(configs) == 0 {
		return nil
	}
	if Sqlc == "never" {
		fmt.Fprintf(out, "queries changed: run sqlc generate for %s, then af gen\n", strings.Join(configs, ", "))
		return nil
	}
	bin, err := exec.LookPath("sqlc")
	if err != nil {
		fmt.Fprintf(out, "queries changed, but sqlc is not on PATH: run sqlc generate for %s, then af gen\n", strings.Join(configs, ", "))
		return nil
	}
	for _, config := range configs {
		cmd := exec.Command(bin, "generate", "-f", filepath.Base(config))
		cmd.Dir = filepath.Dir(config)
		var stderr bytes.Buffer
		cmd.Stdout, cmd.Stderr = out, &stderr
		if err := cmd.Run(); err != nil {
			return errors.New("sqlc generate -f " + config + ": " + strings.TrimSpace(stderr.String()))
		}
		slog.Info("Ran sqlc generate", "config", config)
	}
	sqlcgo.ResetCache()
	return nil
}
